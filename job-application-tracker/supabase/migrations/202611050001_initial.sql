create table if not exists public.profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  phone text not null default '',
  location text not null default '',
  linkedin_url text not null default '',
  portfolio_url text not null default '',
  github_url text not null default '',
  target_roles text not null default '',
  skills text not null default '',
  target_locations text not null default '',
  work_preferences text not null default '',
  contract_types text not null default '',
  availability text not null default '',
  salary_expectation text not null default '',
  cv_url text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
drop policy if exists "Users can view their own profile" on public.profiles;
create policy "Users can view their own profile" on public.profiles for select to authenticated using ((select auth.uid()) = user_id);
drop policy if exists "Users can insert their own profile" on public.profiles;
create policy "Users can insert their own profile" on public.profiles for insert to authenticated with check ((select auth.uid()) = user_id);
drop policy if exists "Users can update their own profile" on public.profiles;
create policy "Users can update their own profile" on public.profiles for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);

create table if not exists public.offers (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  company text not null check (char_length(company) between 1 and 160),
  title text not null check (char_length(title) between 1 and 200),
  url text not null check (url ~* '^https?://'),
  location text not null default '',
  source text not null default '',
  job_type text not null default '',
  salary text not null default '',
  deadline date,
  fit_score integer check (fit_score is null or fit_score between 0 and 100),
  status text not null default 'À examiner'
    check (status in ('À examiner', 'À préparer', 'Prête à envoyer', 'Envoyée', 'Entretien', 'Refusée', 'Relance')),
  notes text not null default '',
  applied_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists offers_user_created_at on public.offers(user_id, created_at desc);
create index if not exists offers_user_status on public.offers(user_id, status);
alter table public.offers enable row level security;
drop policy if exists "Users can view their own offers" on public.offers;
create policy "Users can view their own offers" on public.offers for select to authenticated using ((select auth.uid()) = user_id);
drop policy if exists "Users can insert their own offers" on public.offers;
create policy "Users can insert their own offers" on public.offers for insert to authenticated with check ((select auth.uid()) = user_id);
drop policy if exists "Users can update their own offers" on public.offers;
create policy "Users can update their own offers" on public.offers for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
drop policy if exists "Users can delete their own offers" on public.offers;
create policy "Users can delete their own offers" on public.offers for delete to authenticated using ((select auth.uid()) = user_id);

create or replace function public.create_profile_for_new_user()
returns trigger
language plpgsql
security definer set search_path = ''
as $$
begin
  insert into public.profiles (
    user_id, full_name, phone, location, linkedin_url, portfolio_url, github_url,
    target_roles, skills, target_locations, work_preferences, contract_types,
    availability, salary_expectation, cv_url
  )
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'full_name', ''),
    coalesce(new.raw_user_meta_data ->> 'phone', ''),
    coalesce(new.raw_user_meta_data ->> 'location', ''),
    coalesce(new.raw_user_meta_data ->> 'linkedin_url', ''),
    coalesce(new.raw_user_meta_data ->> 'portfolio_url', ''),
    coalesce(new.raw_user_meta_data ->> 'github_url', ''),
    coalesce(new.raw_user_meta_data ->> 'target_roles', ''),
    coalesce(new.raw_user_meta_data ->> 'skills', ''),
    coalesce(new.raw_user_meta_data ->> 'target_locations', ''),
    coalesce(new.raw_user_meta_data ->> 'work_preferences', ''),
    coalesce(new.raw_user_meta_data ->> 'contract_types', ''),
    coalesce(new.raw_user_meta_data ->> 'availability', ''),
    coalesce(new.raw_user_meta_data ->> 'salary_expectation', ''),
    coalesce(new.raw_user_meta_data ->> 'cv_url', '')
  );
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_profile on auth.users;
create trigger on_auth_user_created_profile
  after insert on auth.users
  for each row execute procedure public.create_profile_for_new_user();

revoke all on function public.create_profile_for_new_user() from public, anon, authenticated;
grant select, insert, update, delete on public.offers to authenticated;
grant select, insert, update on public.profiles to authenticated;
grant usage, select on sequence public.offers_id_seq to authenticated;
